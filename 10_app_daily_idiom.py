##### 기능 구현 함수 #####
def get_daily_quote(target_date):
    # 날짜를 기준으로 매일 동일하지만 날마다 바뀌는 격언을 선택합니다.
    index = target_date.toordinal() % len(QUOTES)
    return QUOTES[index]


##### 메인 함수 #####
def main():
    st.set_page_config(page_title="오늘의 격언", page_icon="🌟")

    st.header("🌟 오늘의 격언")
    st.markdown("---")

    # 사이드바에서 날짜를 선택할 수 있습니다.
    with st.sidebar:
        st.subheader("날짜 선택")
        selected_date = st.date_input("격언을 볼 날짜", value=date.today())

    quote, author = get_daily_quote(selected_date)

    st.caption(f"📅 {selected_date.strftime('%Y년 %m월 %d일')}")

    # 격언을 보기 좋게 표시합니다.
    st.markdown(
        f"""
        <div style="padding: 30px; background-color: #f0f2f6; border-radius: 12px;
                    border-left: 6px solid #ff4b4b; margin: 20px 0;">
            <p style="font-size: 24px; font-weight: 600; color: #262730; line-height: 1.6;">
                “{quote}”
            </p>
            <p style="font-size: 16px; color: #6c6c6c; text-align: right; margin-top: 10px;">
                — {author}
            </p>
        </div>
        """,
        unsafe_allow_html=True,
    )

    st.markdown("---")
    st.info("매일 새로운 격언이 표시됩니다. 사이드바에서 다른 날짜를 선택해 보세요!")


if __name__ == "__main__":
    main()
